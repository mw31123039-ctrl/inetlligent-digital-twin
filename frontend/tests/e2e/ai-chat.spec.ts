import { test, expect, type Page } from '@playwright/test'

test.beforeEach(async ({ page, request }) => {
  const response = await request.get('/api/status')
  test.skip(!response.ok(), 'Start the Laravel and Python services to run full-stack tests.')
  const status = await response.json()
  test.skip(!status.available || status.provider_configured, 'Run these synthetic integration tests with AI_PROVIDER=disabled; no paid AI calls are made.')
  await page.goto('/')
  await page.getByRole('button', { name: 'AI assistant', exact: true }).click()
})

async function register(page: Page) {
  await page.getByRole('button', { name: 'Create an account', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`e2e-${crypto.randomUUID()}@example.test`)
  await page.getByLabel('Password', { exact: true }).fill('synthetic-test-password-12345')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: /I understand that my answers/ }).check()
}

test('body context, one question at a time, correction, explicit save consent and deletion', async ({ page }) => {
  await register(page)
  const input = page.getByRole('textbox', { name: 'Describe your symptoms or answer the question' })
  await input.fill('My eyes feel dry after screens')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).toContainText('Are you having sudden loss of sight')
  await expect(page.getByText('No AI credentials are configured.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'No', exact: true }).click()
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).toContainText('Where exactly do you feel it')
  await input.fill('Both eyes')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).toContainText('When did this first start')
  await expect(page.getByRole('combobox', { name: 'Affected side' })).toHaveValue('both')
  await page.getByRole('button', { name: 'Correct answer: My eyes feel dry after screens', exact: true }).click()
  await input.fill('My eyes feel mildly itchy')
  await page.getByRole('button', { name: 'Update', exact: true }).click()
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).not.toContainText('Both eyes')
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).toContainText('My eyes feel mildly itchy')
  await expect(page.getByRole('combobox', { name: 'Affected side' })).toHaveValue('unknown')
  await expect(page.getByRole('button', { name: 'Save with consent', exact: true })).toBeDisabled()
  await page.getByRole('checkbox', { name: /I consent to saving this conversation and assessment/ }).check()
  await page.getByRole('button', { name: 'Save with consent', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Saved with consent', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Assessments', exact: true }).click()
  await page.getByRole('button', { name: 'View saved summary', exact: true }).click()
  await expect(page.getByRole('region', { name: 'AI assessment summary', exact: true })).toContainText('My eyes feel mildly itchy')
  await expect(input).toBeDisabled()
  await page.getByRole('button', { name: 'Delete conversation', exact: true }).click()
  await expect(page.getByRole('region', { name: 'AI assessment summary', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Assessments', exact: true }).click()
  await expect(page.getByText('No conversations saved.', { exact: false })).toBeVisible()
})

test('urgent symptoms interrupt normal questions even without an AI provider', async ({ page }) => {
  await register(page)
  await page.getByRole('button', { name: 'Chest', exact: true }).click()
  await page.getByRole('textbox', { name: 'Describe your symptoms or answer the question' }).fill('I have severe chest pressure and cannot breathe')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Seek emergency help now')
  await expect(page.getByRole('alert')).toContainText('Do not wait to finish this chat')
  await expect(page.getByRole('textbox', { name: 'Describe your symptoms or answer the question' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'No', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Delete conversation', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('failed API keeps the input, region changes reset context, and logout clears private state', async ({ page }) => {
  await register(page)
  await page.route('**/api/conversations', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Assessment service unavailable. No result generated.' }) }))
  const input = page.getByRole('textbox', { name: 'Describe your symptoms or answer the question' })
  await input.fill('A mild tight feeling')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No result generated')
  await expect(input).toHaveValue('A mild tight feeling')
  await page.unroute('**/api/conversations')
  await page.getByRole('button', { name: 'Legs', exact: true }).click()
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).toContainText('You selected your legs')
  await expect(input).toHaveValue('')
  await input.fill('My leg feels mildly tight')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).toContainText('new swelling in one leg')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByLabel('Email', { exact: true })).toBeVisible()
  await expect(page.getByRole('log', { name: 'AI symptom conversation' })).not.toContainText('My leg feels mildly tight')
  await expect(input).toBeDisabled()
  expect((await page.request.get('/api/me')).status()).toBe(401)
})
