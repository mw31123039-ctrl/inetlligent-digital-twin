import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: 'Scripted demo', exact: true }).click()
})

test('eyes conversation, live pain summary, local save, export, and history', async ({ page }) => {
  const runtimeErrors: string[] = []
  page.on('pageerror', e => runtimeErrors.push(e.message))
  await expect(page.getByRole('heading', { name: 'Where does it hurt?' })).toBeVisible()
  await page.getByRole('button', { name: 'My eyes hurt', exact: true }).click()
  await expect(page.getByText('Is the pain in one eye or both?', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Both eyes', exact: true }).click()
  await page.getByRole('button', { name: 'A few days', exact: true }).click()
  await page.getByRole('button', { name: 'Comes and goes', exact: true }).click()
  await expect(page.getByText('Your demo assessment is complete', { exact: true })).toBeVisible()
  await page.getByRole('slider', { name: 'Pain level' }).fill('7')
  const summary = page.getByRole('region', { name: 'Assessment summary', exact: true })
  await expect(summary).toContainText('Pain 7/10')
  await expect(summary).toContainText('Both eyes')
  await page.getByRole('checkbox', { name: 'I consent to saving this scripted demo conversation in this browser until I delete it.' }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Saved', exact: true })).toBeDisabled()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export assessment as JSON' }).click()
  expect((await downloadPromise).suggestedFilename()).toMatch(/^humantwin-eyes-.*\.json$/)
  await page.getByRole('button', { name: 'Assessments', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Eyes assessment', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await page.getByRole('button', { name: 'View summary' }).click()
  await expect(page.getByRole('dialog')).toContainText('7 out of 10')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Delete Eyes assessment' }).click()
  await expect(page.getByText('Your story starts here')).toBeVisible()
  expect(runtimeErrors).toEqual([])
})

test('2D SVG selections, front/back, zoom and empty states', async ({ page }) => {
  await page.getByRole('button', { name: '2D', exact: true }).click()
  const points: Record<string, [number, number]> = { head: [200, 45], chest: [200, 200], abdomen: [200, 300], arms: [114, 235], legs: [175, 435], eyes: [183, 82] }
  for (const [region, point] of Object.entries(points)) {
    const position = await page.locator(`svg.body-svg [data-region="${region}"]`).evaluate((node, p) => {
      const projected = new DOMPoint(p[0], p[1]).matrixTransform((node as SVGGraphicsElement).getScreenCTM()!)
      return { x: projected.x, y: projected.y }
    }, point)
    await page.mouse.click(position.x, position.y)
    await expect(page.locator('.region-selector button.selected')).toContainText(region, { ignoreCase: true })
  }
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Back', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('svg [data-region="eyes"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Front', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Clear selected area and conversation' }).click()
  await expect(page.getByText('Let’s start with an area')).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Describe your symptoms', exact: true })).toBeDisabled()
})

test('3D raycast selection, rotation, WebGL context error and 2D fallback', async ({ page }) => {
  const canvas = page.locator('.body-canvas canvas')
  await expect(canvas).toBeVisible()
  await expect(page.getByText('Preparing your digital twin')).not.toBeVisible()
  const box = (await canvas.boundingBox())!
  await canvas.click({ position: { x: box.width / 2, y: box.height * .30 } })
  await expect(page.locator('.region-selector button.selected')).toHaveText('Chest')
  await page.locator('.body-canvas').focus()
  await page.keyboard.press('ArrowRight')
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByText('POSTERIOR VIEW')).toBeVisible()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await canvas.evaluate(node => (node as HTMLCanvasElement).getContext('webgl2')?.getExtension('WEBGL_lose_context')?.loseContext())
  await expect(page.getByText('3D viewer unavailable', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Use 2D instead' }).click()
  await expect(page.locator('.body-svg')).toBeVisible()
})

test('simulated response error retries safely and region changes cancel stale replies', async ({ page }) => {
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('switch', { name: 'Simulate next response error' }).click()
  await page.getByRole('button', { name: 'Open body explorer' }).click()
  await page.getByRole('textbox', { name: 'Describe your symptoms', exact: true }).fill('My eyes hurt')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('could not be loaded')
  await page.getByRole('button', { name: 'Retry response' }).click()
  await expect(page.getByRole('button', { name: 'Both eyes', exact: true })).toBeVisible()
  await expect(page.locator('.message-row.user')).toHaveCount(1)
  await page.getByRole('button', { name: 'Both eyes', exact: true }).click()
  await page.getByRole('button', { name: 'Legs', exact: true }).click()
  await expect(page.getByRole('button', { name: 'My leg hurts', exact: true })).toBeVisible()
  await page.waitForTimeout(800)
  await expect(page.locator('.message-row')).toHaveCount(1)
  await expect(page.locator('.conversation')).toContainText('You selected your legs')
})

