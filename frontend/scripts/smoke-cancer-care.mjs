// Actual local models + public examples. No personal patient data or mocked AI.
import assert from 'node:assert/strict'
import { createHash, randomBytes } from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import { chromium, expect as baseExpect } from '@playwright/test'
const expect = baseExpect.configure({ timeout: 30000 })
const base = process.env.HUMANTWIN_CANCER_URL || 'http://127.0.0.1:5173'
const output = path.resolve('test-results/cancer-care')
await fs.mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'chrome' : undefined, headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1500, height: 1080 }, acceptDownloads: true })
page.setDefaultTimeout(30000)
const errors = [], imageRequests = [], evidenceRequests = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => {
  if (request.method() === 'POST' && request.url().endsWith('/api/cancer/analyze')) imageRequests.push(request)
  if (request.method() === 'POST' && request.url().endsWith('/api/cancer/knowledge')) evidenceRequests.push(request)
})
async function screenshot(name) {
  await page.evaluate(() => { window.scrollTo(0, 0); if (document.activeElement instanceof HTMLElement) document.activeElement.blur() })
  await page.screenshot({ path: path.join(output, name), fullPage: true })
}
try {
  await page.goto(base + '/#cancer')
  await expect(page.getByRole('heading', { name: 'Cancer care intelligence' })).toBeVisible()
  await expect(page.getByLabel('Input type')).toHaveValue('dermoscopy')
  assert.equal(await page.locator('.brand-mark').getAttribute('src'), '/brand/humantwin-mark.svg')
  assert.ok(await page.locator('.care-analysis-intro p').evaluate(element => parseFloat(getComputedStyle(element).fontSize)) >= 17)
  await page.getByRole('button', { name: 'Increase text size' }).click()
  assert.ok(await page.locator('.care-analysis-intro p').evaluate(element => parseFloat(getComputedStyle(element).fontSize)) >= 20)
  await page.getByRole('button', { name: 'Use standard text size' }).click()
  await screenshot('desktop-upload.png')
  await page.locator('.header-sign-in').click()
  await page.getByRole('dialog').getByRole('button', { name: 'Create an account', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Create your account' })
  await dialog.getByLabel('Email', { exact: true }).fill(`care-check-${randomBytes(8).toString('hex')}@example.invalid`)
  await dialog.getByLabel('Password', { exact: true }).fill(randomBytes(20).toString('base64url'))
  await dialog.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.locator('.profile-button')).toContainText('Member')

  const largeImage = Buffer.from(await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 4032; canvas.height = 3024
    const context = canvas.getContext('2d'); context.fillStyle = '#96afa1'; context.fillRect(0, 0, 4032, 3024)
    context.fillStyle = '#fff'; context.font = '100px sans-serif'; context.fillText('SYNTHETIC FILE HANDLING ONLY', 150, 1500)
    return canvas.toDataURL('image/png').split(',')[1]
  }), 'base64')
  const chooserEvent = page.waitForEvent('filechooser')
  await page.locator('.care-hero').getByRole('button', { name: 'Upload an image', exact: true }).click()
  await (await chooserEvent).setFiles({ name: 'synthetic-large.png', mimeType: 'image/png', buffer: largeImage })
  await expect(page.getByAltText('Attached research image preview')).toBeVisible()
  await expect(page.locator('.care-viewer-top')).toContainText('2048 × 1536')
  await expect(page.getByText('Resized from 4032 × 3024 to 2048 × 1536. The original file is not uploaded.')).toBeVisible()
  assert.equal(imageRequests.length, 0)

  await page.getByRole('button', { name: 'Load a public oral example', exact: true }).click()
  await expect(page.getByLabel('Input type')).toHaveValue('oral_photo')
  await expect(page.locator('.care-reference-attribution')).toContainText('CC BY 4.0')
  await expect(page.getByRole('checkbox', { name: /^I permit sending/ })).not.toBeChecked()
  await page.getByRole('checkbox', { name: /^I confirm this image/ }).check()
  await page.getByRole('checkbox', { name: /^I understand this is experimental/ }).check()
  await page.getByRole('checkbox', { name: /^I permit sending/ }).check()
  const imageEvent = page.waitForResponse(response => response.url().endsWith('/api/cancer/analyze') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Run research model', exact: true }).click()
  const imageReply = await imageEvent, imageResult = await imageReply.json()
  assert.equal(imageReply.status(), 200)
  assert.equal(imageResult.modality, 'oral_photo')
  await expect(page.getByRole('heading', { name: 'Model findings', exact: true })).toBeVisible()
  await expect(page.locator('svg.cancer-heatmap rect')).toHaveCount(16)
  await screenshot('desktop-model-review.png')

  await page.locator('.care-symptom-checks summary').click()
  const severe = page.getByRole('checkbox', { name: /^Severe difficulty breathing/ })
  await severe.check()
  await expect(page.locator('.care-emergency').getByRole('heading', { name: 'Seek emergency care now' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Run research model', exact: true })).toBeDisabled()
  await severe.uncheck()
  await expect(page.locator('.care-emergency')).toBeVisible()
  await page.getByRole('tab', { name: /Care & next steps/ }).click()
  await expect(page.locator('.care-plan-priority')).toContainText('Seek emergency care now')
  await page.getByRole('tab', { name: /Analyze an image/ }).click()
  await page.getByRole('button', { name: 'Clear case', exact: true }).click()
  await expect(page.locator('.care-emergency')).toHaveCount(0)
  await expect(page.getByAltText('Attached research image preview')).toHaveCount(0)

  await page.getByRole('tab', { name: /Cancer knowledge/ }).click()
  await expect(page.getByRole('heading', { name: 'Understand the questions behind a diagnosis.' })).toBeVisible()
  await page.getByLabel('Search cancer knowledge').fill('PSA')
  await expect(page.locator('.care-topic-detail h3')).toHaveText('Prostate')
  await page.getByLabel('Search cancer knowledge').fill('')
  await expect(page.getByText('Local AI search ready', { exact: true })).toBeVisible()
  await page.getByLabel('Your cancer information question').fill('Which tests investigate a mouth ulcer lasting weeks?')
  await page.getByRole('checkbox', { name: /^I permit processing this question/ }).check()
  const knowledgeEvent = page.waitForResponse(response => response.url().endsWith('/api/cancer/knowledge') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Ask local AI', exact: true }).click()
  const knowledgeReply = await knowledgeEvent, knowledge = await knowledgeReply.json()
  assert.equal(knowledgeReply.status(), 200)
  assert.equal(knowledge.matches[0].record_id, 'oral')
  assert.equal(knowledge.question_saved, false)
  assert.equal(knowledge.question_sha256, createHash('sha256').update(evidenceRequests.at(-1).postDataJSON().question).digest('hex'))
  assert.deepEqual(Object.keys(evidenceRequests.at(-1).postDataJSON()).sort(), ['question', 'consent_local'].sort())
  await expect(page.locator('.care-ai-answer')).toContainText('Mouth & oral cavity')
  await expect(page.locator('.care-topic-detail h3')).toHaveText('Mouth & oral cavity')
  await screenshot('desktop-evidence-assistant.png')

  await page.getByLabel('Your cancer information question').fill('What guide explains bladder cancer and cystoscopy?')
  const namedTopicEvent = page.waitForResponse(response => response.url().endsWith('/api/cancer/knowledge') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Ask local AI', exact: true }).click()
  const namedTopicReply = await namedTopicEvent, namedTopicResult = await namedTopicReply.json()
  assert.equal(namedTopicReply.status(), 200)
  assert.equal(namedTopicResult.matches[0].record_id, 'bladder')
  await expect(page.locator('.care-topic-detail h3')).toHaveText('Bladder')

  await page.getByLabel('Search cancer knowledge').fill('brain')
  await expect(page.locator('.care-topic-detail h3')).toContainText('Brain')
  await page.getByRole('button', { name: 'Prepare a review plan', exact: true }).click()
  await expect(page.locator('.care-plan-view')).toContainText('Neurology')
  await expect(page.locator('.care-plan-view')).toContainText('No matching image-model result in this case.')
  await page.getByRole('checkbox', { name: /^I permit downloading/ }).check()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export research JSON', exact: true }).click()
  const record = JSON.parse(await fs.readFile(await (await downloadEvent).path(), 'utf8'))
  assert.equal(record.review_guide.topic_id, 'brain'); assert.equal(record.cancer_diagnosis, null)
  assert.equal(record.inference_state, 'not-run'); assert.equal(record.image, null)
  assert.equal(record.reported_concerns.absence_not_established_for_unchecked_items, true)
  await screenshot('desktop-review-plan.png')
  await page.getByRole('tab', { name: /Analyze an image/ }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await screenshot('mobile-upload.png')
  await page.getByRole('tab', { name: /Cancer knowledge/ }).click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
  await screenshot('mobile-knowledge.png')
  assert.deepEqual(errors, [])
  console.log('Cancer care checks passed: visible upload chooser, safe resize, licensed example, real inference, emergency precedence, source library, actual semantic AI, review export, larger type/logo and mobile layout.')
} finally { await browser.close() }
