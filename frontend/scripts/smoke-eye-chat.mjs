import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs'
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const context=await browser.newContext({viewport:{width:1500,height:1100}})
const page=await context.newPage(),errors=[]
page.on('pageerror',error=>errors.push(error.message));page.setDefaultTimeout(15000)
const url=process.env.HUMANTWIN_EYE_URL||'http://127.0.0.1:5174'
fs.mkdirSync('test-results',{recursive:true})
try{
 await page.goto(url)
 const card=page.getByTestId('inline-eye-assistant')
 await card.waitFor();assert.match(await card.innerText(),/Symptom assistant/)
 assert.equal((await card.getByTestId('eye-pain-score').innerText()).replace(/\s/g,''),'—/10')
 await card.locator('.eye-ack input').check()
 await card.locator('.eye-answer-input input').fill('My left eye feels dry and gritty')
 await card.getByRole('button',{name:'Send answer',exact:false}).click()
 const before=await card.locator('.eye-question h4').innerText()
 await card.locator('.eye-answer-input input').fill('Explain the cornea')
 await card.getByRole('button',{name:'Send answer',exact:false}).click()
 assert.equal(await card.locator('.eye-question h4').innerText(),before)
 assert.match(await card.locator('.eye-chat-log').innerText(),/transparent front surface/i)
 assert.ok(await card.locator('.eye-chat-source').count()>0)
 await card.locator('.eye-pain-manual-toggle').click()
 await card.getByRole('button',{name:'Pain 6 out of 10',exact:true}).click()
 assert.match(await card.getByTestId('eye-pain-feedback').innerText(),/6\/10: moderate pain/i)
 assert.match(await card.locator('.eye-chat-log').innerText(),/6\/10: moderate pain/i)
 await page.getByRole('button',{name:'Eyes',exact:true}).click()
 const atlas=page.locator('.eye-part-detail .eye-atlas')
 await atlas.waitFor()
 assert.equal(await atlas.locator('[data-structure-id]').count(),63)
 await atlas.locator('.eye-canvas canvas').waitFor()
 await atlas.locator('[data-structure-id="eye.lens"]').click()
 assert.equal(await atlas.locator('.eye-model-stage').getAttribute('data-view'),'section')
 await atlas.locator('[data-structure-id="eye.corneal-endothelium"]').click()
 assert.equal(await atlas.locator('.eye-model-stage').getAttribute('data-view'),'corneal-detail')
 await atlas.locator('[data-structure-id="eye.photoreceptors"]').click()
 assert.equal(await atlas.locator('.eye-model-stage').getAttribute('data-view'),'retinal-detail')
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'test-results/eye-chat-desktop.png',fullPage:true})
 await card.getByRole('button',{name:/3D anatomy/}).click()
 await page.locator('.eye-workspace').waitFor()
 await page.locator('.eye-main-tabs button').nth(1).click()
 assert.match(await page.getByTestId('eye-pain-feedback').innerText(),/6\/10: moderate pain/i)
 assert.match(await page.locator('.eye-chat-log').innerText(),/Explain the cornea/)
 await page.getByRole('button',{name:'Back to body explorer',exact:false}).click()
 assert.match(await card.getByTestId('eye-pain-feedback').innerText(),/6\/10: moderate pain/i)
 const phoneContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
 const phone=await phoneContext.newPage();phone.on('pageerror',e=>errors.push(e.message));await phone.goto(url+'/#eye-chat')
 await phone.locator('.eye-part-detail .eye-atlas').waitFor()
 await phone.locator('.eye-part-detail [data-structure-id="eye.lens"]').tap()
 assert.equal(await phone.locator('.eye-part-detail .eye-model-stage').getAttribute('data-view'),'section')
 await phone.locator('.eye-ack input').check()
 await phone.locator('.eye-pain-manual-toggle').tap()
 await phone.getByRole('button',{name:'Pain 0 out of 10',exact:true}).tap()
 assert.match(await phone.getByTestId('eye-pain-feedback').innerText(),/0\/10: no pain/i)
 assert.ok(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2))
 await phone.evaluate(()=>window.scrollTo(0,0));await phone.screenshot({path:'test-results/eye-chat-mobile.png',fullPage:true});await phoneContext.close()
 assert.deepEqual(errors,[])
 console.log('PASS: original assistant replaced; educational answers preserve intake; reported pain score and feedback synchronize; all 63 structures in main 3D; internal/micro views; draft survives workspace switches; mobile touch. No page errors.')
}catch(error){console.error(JSON.stringify(errors));await page.screenshot({path:'test-results/eye-chat-failure.png',fullPage:true});throw error}
finally{await browser.close()}
